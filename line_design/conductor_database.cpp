std::optional<ConductorDatabase::Record>
ConductorDatabase::lookupByName(const std::string& code) const
{
    auto it = byCode_.find(toLower(code));
    if (it != byCode_.end()) return it->second;
    return std::nullopt;
}

std::optional<ConductorDatabase::Record>
ConductorDatabase::lookupByCode(const std::string& partNumber) const
{
    auto it = byName_.find(toLower(partNumber));
    if (it != byName_.end()) return it->second;
    return std::nullopt;
}

std::vector<ConductorDatabase::Record>
ConductorDatabase::lookupByType(Type t) const
{
    std::vector<Record> result;
    for (const auto& r : all_) {
        if (r.type == t) result.push_back(r);
    }
    return result;
}

ConductorDatabase::Record
ConductorDatabase::lookupByArea(double targetArea_mm2) const
{
    if (all_.empty()) throw std::runtime_error("database empty");
    Record closest = all_[0];
    double minDiff = std::abs(all_[0].area_mm2 - targetArea_mm2);
    for (const auto& r : all_) {
        double diff = std::abs(r.area_mm2 - targetArea_mm2);
        if (diff < minDiff) {
            minDiff = diff;
            closest = r;
        }
    }
    return closest;
}

