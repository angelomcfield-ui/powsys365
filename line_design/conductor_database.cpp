std::string
ConductorDatabase::typeToString(Type t)
{
    switch (t) {
        case Type::ACSR:    return "ACSR";
        case Type::AAC:     return "AAC";
        case Type::AAAC:    return "AAAC";
        case Type::ACSS:    return "ACSS";
        case Type::ACAR:    return "ACAR";
        case Type::ACSR_AW: return "ACSR/AW";
        case Type::AACSR:   return "AACSR";
        case Type::HARDDrawn: return "Hard Drawn";
    }
    return "Unknown";
}

std::string
ConductorDatabase::toLower(const std::string& s)
{
    std::string r = s;
    for (auto& c : r) c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    return r;
}

/* ================================================================
   Constructor – populate all records
   ================================================================ */

ConductorDatabase::ConductorDatabase()
{
    populateACSR();
    populateAAC();
    populateAAAC();
    populateACSS();
    populateACAR();
    populateOthers();
}

